#!/usr/bin/env python3
"""Convert a TFLite model into a C byte array for TFLite Micro."""

from __future__ import annotations

import argparse
from pathlib import Path


def convert_model(input_path: Path, output_path: Path) -> None:
    """Write a binary model as a C++ source file with fixed symbols."""
    data = input_path.read_bytes()
    rows = []
    for offset in range(0, len(data), 12):
        chunk = data[offset : offset + 12]
        values = ", ".join(f"0x{value:02x}" for value in chunk)
        rows.append(f"  {values},")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        "// Generated by tools/tflite_to_c.py.\n"
        "\n"
        "extern const unsigned char g_cifar_model[] = {\n"
        + "\n".join(rows)
        + "\n};\n"
        f"extern const unsigned int g_cifar_model_len = {len(data)};\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    convert_model(args.input, args.output)


if __name__ == "__main__":
    main()
